def expand_query_with_glossary(query: str) -> tuple[str, list[str]]:
    """Return expanded search query and matched glossary notes for prompt context."""
    additions: list[str] = []
    matched_notes: list[str] = []

    tokens = set(re.findall(r"[A-Za-zА-Яа-яЁё0-9-]+", query))
    for abbr, full in GLOSSARY.items():
        if abbr in tokens or (len(abbr) >= 3 and abbr.lower() in {t.lower() for t in tokens}):
            additions.append(full)
            matched_notes.append(f"{abbr} = {full}")

    # Reverse lookup: if user wrote full name, add common abbreviation
    q_low = query.lower()
    reverse_map = {
        "руководитель проекта": "РП",
        "аккаунт-менеджер": "АМ",
        "техническое задание": "ТЗ",
        "расчёт трудозатрат": "РТЗ",
        "расчет трудозатрат": "РТЗ",
        "заявка на пресейл": "ЗнП",
        "гарантийное письмо": "ГП",
        "главный инженер": "ГИП",
        "служба безопасности": "СБ",
    }
    for phrase, abbr in reverse_map.items():
        if phrase in q_low and abbr not in tokens:
            additions.append(abbr)

    for pattern, extra in COLLOQUIAL_EXPANSIONS:
        if pattern.search(query):
            additions.append(extra)

    expanded = query
    if additions:
        expanded = f"{query} | {' '.join(dict.fromkeys(additions))}"
    return expanded, matched_notes[:12]


def glossary_prompt_block(matched_notes: list[str]) -> str:
    if not matched_notes:
        return "РП=Руководитель проекта, АМ=Аккаунт-менеджер, SS=Solution Sales, ПА=Пресейл-архитектор, TPS=Технический пресейл-специалист, РТЗ=Расчёт трудозатрат, ЗнП=Заявка на пресейл, ГИП=Главный инженер проекта, ДИБ=Дирекция ИБ, ДБРЦТ=Департамент бизнес-решений и цифровой трансформации."
    return "; ".join(matched_notes)
